"""Outreach tracker: one SQLite file (outreach.db) holding every company, person, touch and next step.

    python3 outreach/ot.py status                 # where things stand + what's due
    python3 outreach/ot.py person "Jane Doe" # one person's full history
    python3 outreach/ot.py touch "Jane Doe" email sent --subject "..." --apollo-id ID --note "..."
    python3 outreach/ot.py task "Jane Doe" "Call office line" --due 2026-10-14 --channel call
    python3 outreach/ot.py done <task_id>
    python3 outreach/ot.py log "free-text event"  # anything worth remembering
    python3 outreach/ot.py readme                 # regenerate outreach/STATUS.md from the db

Touch statuses: drafted, sent, opened, replied, bounced, meeting, no, connected, called, voicemail.
"""
import argparse
import datetime as dt
import os
import sqlite3
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DB = os.path.join(HERE, "outreach.db")

SCHEMA = """
CREATE TABLE IF NOT EXISTS companies (
  id INTEGER PRIMARY KEY, name TEXT UNIQUE NOT NULL, market TEXT, segment TEXT, owner TEXT,
  size INTEGER, week TEXT, why TEXT, sales_nav_list TEXT, apollo_list TEXT, stage TEXT DEFAULT 'targeted');
CREATE TABLE IF NOT EXISTS people (
  id INTEGER PRIMARY KEY, company_id INTEGER REFERENCES companies(id), name TEXT NOT NULL, title TEXT,
  email TEXT, email_status TEXT, phone TEXT, linkedin TEXT, connection TEXT,
  apollo_contact_id TEXT, apollo_person_id TEXT, note TEXT, stage TEXT DEFAULT 'new', UNIQUE(name, company_id));
CREATE TABLE IF NOT EXISTS touches (
  id INTEGER PRIMARY KEY, person_id INTEGER REFERENCES people(id), at TEXT, channel TEXT, status TEXT,
  subject TEXT, apollo_message_id TEXT, note TEXT);
CREATE TABLE IF NOT EXISTS tasks (
  id INTEGER PRIMARY KEY, person_id INTEGER REFERENCES people(id), channel TEXT, what TEXT, due TEXT,
  done INTEGER DEFAULT 0, created TEXT);
CREATE TABLE IF NOT EXISTS log (id INTEGER PRIMARY KEY, at TEXT, event TEXT);
"""


def conn():
    c = sqlite3.connect(DB)
    c.row_factory = sqlite3.Row
    c.executescript(SCHEMA)
    return c


def now():
    return dt.datetime.now().strftime("%Y-%m-%d %H:%M")


def person_id(c, name):
    rows = c.execute("SELECT id FROM people WHERE name = ?", (name,)).fetchall()
    if len(rows) != 1:
        sys.exit(f"expected one person named {name!r}, found {len(rows)}")
    return rows[0]["id"]


def status_text(c):
    out = []
    today = dt.date.today().isoformat()
    out.append(f"# Outreach status (generated {now()})\n")
    out.append("State lives in `outreach/outreach.db`; edit it with `python3 outreach/ot.py`. "
               "This file is regenerated by `ot.py readme`.\n")
    out.append("## Pipeline\n")
    out.append("| Segment | Companies | People | With email | Emails sent | Replies | Meetings |")
    out.append("|---|---|---|---|---|---|---|")
    for seg in [r["segment"] for r in c.execute("SELECT DISTINCT segment FROM companies ORDER BY segment")]:
        q = lambda sql: c.execute(sql, (seg,)).fetchone()[0]
        people = "SELECT COUNT(*) FROM people p JOIN companies co ON co.id=p.company_id WHERE co.segment=?"
        # Count people, not touches, so re-logged sends don't double count. Keep SQL literals
        # single-quoted: a double-quoted "email" resolves to the people.email column.
        touched = ("SELECT COUNT(DISTINCT p.id) FROM touches t JOIN people p ON p.id=t.person_id "
                   "JOIN companies co ON co.id=p.company_id WHERE co.segment=? AND ")
        cols = [
            "SELECT COUNT(*) FROM companies WHERE segment=?",
            people,
            people + " AND p.email IS NOT NULL AND p.email <> ''",
            touched + "t.channel = 'email' AND t.status = 'sent'",
            touched + "t.status = 'replied'",
            touched + "t.status = 'meeting'",
        ]
        out.append(f"| {seg} | " + " | ".join(str(q(sql)) for sql in cols) + " |")
    out.append("\n## Open tasks (next steps)\n")
    out.append("| # | Due | Channel | Person | Company | What |")
    out.append("|---|---|---|---|---|---|")
    for r in c.execute("""SELECT t.id, t.due, t.channel, p.name, co.name AS company, t.what FROM tasks t
                          LEFT JOIN people p ON p.id=t.person_id LEFT JOIN companies co ON co.id=p.company_id
                          WHERE t.done=0 ORDER BY t.due, t.id"""):
        flag = " ⚠ overdue" if r["due"] and r["due"] < today else ""
        out.append(f"| {r['id']} | {r['due'] or ''}{flag} | {r['channel'] or ''} | {r['name'] or '-'} | {r['company'] or '-'} | {r['what']} |")
    out.append("\n## Recent touches\n")
    out.append("| When | Person | Company | Channel | Status | Subject / note |")
    out.append("|---|---|---|---|---|---|")
    for r in c.execute("""SELECT t.at, p.name, co.name AS company, t.channel, t.status, COALESCE(t.subject, t.note, '') AS s
                          FROM touches t JOIN people p ON p.id=t.person_id JOIN companies co ON co.id=p.company_id
                          ORDER BY t.at DESC, t.id DESC LIMIT 30"""):
        out.append(f"| {r['at']} | {r['name']} | {r['company']} | {r['channel']} | {r['status']} | {r['s']} |")
    out.append("\n## Log\n")
    for r in c.execute("SELECT at, event FROM log ORDER BY id DESC LIMIT 30"):
        out.append(f"- {r['at']} — {r['event']}")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("status")
    sub.add_parser("readme")
    p = sub.add_parser("person"); p.add_argument("name")
    p = sub.add_parser("touch"); p.add_argument("name"); p.add_argument("channel"); p.add_argument("status")
    p.add_argument("--subject"); p.add_argument("--apollo-id"); p.add_argument("--note"); p.add_argument("--at")
    p = sub.add_parser("task"); p.add_argument("name"); p.add_argument("what"); p.add_argument("--due"); p.add_argument("--channel")
    p = sub.add_parser("done"); p.add_argument("task_id", type=int)
    p = sub.add_parser("log"); p.add_argument("event")
    a = ap.parse_args()
    c = conn()
    if a.cmd == "status":
        print(status_text(c))
    elif a.cmd == "readme":
        open(os.path.join(HERE, "STATUS.md"), "w").write(status_text(c))
        print("wrote outreach/STATUS.md")
    elif a.cmd == "person":
        pid = person_id(c, a.name)
        print(dict(c.execute("SELECT p.*, co.name AS company FROM people p JOIN companies co ON co.id=p.company_id WHERE p.id=?", (pid,)).fetchone()))
        for r in c.execute("SELECT * FROM touches WHERE person_id=? ORDER BY at", (pid,)):
            print("  touch:", dict(r))
        for r in c.execute("SELECT * FROM tasks WHERE person_id=? ORDER BY due", (pid,)):
            print("  task:", dict(r))
    elif a.cmd == "touch":
        pid = person_id(c, a.name)
        c.execute("INSERT INTO touches (person_id, at, channel, status, subject, apollo_message_id, note) VALUES (?,?,?,?,?,?,?)",
                  (pid, a.at or now(), a.channel, a.status, a.subject, a.apollo_id, a.note))
        c.execute("UPDATE people SET stage=? WHERE id=?", (a.status, pid))
        c.commit()
    elif a.cmd == "task":
        pid = person_id(c, a.name) if a.name != "-" else None
        c.execute("INSERT INTO tasks (person_id, channel, what, due, created) VALUES (?,?,?,?,?)", (pid, a.channel, a.what, a.due, now()))
        c.commit()
    elif a.cmd == "done":
        c.execute("UPDATE tasks SET done=1 WHERE id=?", (a.task_id,))
        c.commit()
    elif a.cmd == "log":
        c.execute("INSERT INTO log (at, event) VALUES (?,?)", (now(), a.event))
        c.commit()


if __name__ == "__main__":
    main()
